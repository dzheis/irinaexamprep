import type { Metadata } from "next";
import Link from "next/link";
import { renderRichText } from "@storyblok/react";
import { getTextPageFromStoryblok } from "@/lib/text-page-storyblok";

export const metadata: Metadata = {
  title: "Оплата, получение услуги и возврат | Irina Exam Prep",
  description:
    "Способы получения образовательных услуг, условия отказа и возврата денежных средств",
};

const DEFAULT_TITLE = "Оплата, получение услуги и возврат";
const SUBTITLE_CLASS = "font-normal text-theme-accent mb-6 text-justify";

export default async function PaymentRefundPage() {
  const data = await getTextPageFromStoryblok("payment-refund", DEFAULT_TITLE);
  const contentHtml =
    data.contentRichText != null
      ? (renderRichText(data.contentRichText as unknown as Parameters<typeof renderRichText>[0]) ??
        "")
      : null;

  return (
    <div className="min-h-screen">
      <div className="pt-24 md:pt-28 pb-16">
        <article className="max-w-3xl mx-auto px-6 text-theme">
          <h1 className="text-3xl md:text-4xl font-bold mb-6">{data.title}</h1>

          {contentHtml ? (
            <>
              {data.customFields?.subtitle != null && (
                <h2 className={SUBTITLE_CLASS}>{data.customFields.subtitle}</h2>
              )}
              <section
                className="prose prose-theme max-w-none text-theme space-y-6 [&_p]:text-justify [&_ul]:pl-6 [&_h2]:text-xl [&_h2]:font-bold [&_h2]:mt-8 [&_h2]:mb-2 [&_h3]:text-lg [&_h3]:font-semibold [&_h3]:mt-4 [&_h3]:mb-2"
                dangerouslySetInnerHTML={{ __html: contentHtml }}
              />
            </>
          ) : (
            <PaymentRefundStaticContent />
          )}

          <div className="mt-10 flex flex-wrap gap-3">
            <Link
              href="/"
              className="btn-secondary !px-5 !py-2.5 text-sm md:text-base no-underline inline-flex items-center gap-2"
            >
              ← Вернуться на главную
            </Link>
          </div>
        </article>
      </div>
    </div>
  );
}

